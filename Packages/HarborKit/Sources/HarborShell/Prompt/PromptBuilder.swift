import Foundation
import HarborCore

/// Renders a `PromptConfig` as a script for one shell.
protocol PromptRenderer: Sendable {
    func render(_ config: PromptConfig) -> String
}

/// Turns one shell-agnostic prompt design into zsh, bash and fish prompt files.
///
/// Dynamic values (git branch, venv name…) are always inserted through variables, never
/// spliced into prompt strings, so a hostile branch name like `$(rm -rf ~)` is inert.
public enum PromptBuilder {
    public static func render(_ config: PromptConfig, for shell: ShellKind) -> String? {
        renderer(for: shell)?.render(config)
    }

    static func renderer(for shell: ShellKind) -> (any PromptRenderer)? {
        switch shell {
        case .zsh: ZshPromptRenderer()
        case .bash: BashPromptRenderer()
        case .fish: FishPromptRenderer()
        case .other: nil
        }
    }

    static func header(for config: PromptConfig) -> String {
        """
        # Generated by \(AppIdentity.name) from the “\(config.presetName ?? "Custom")” prompt design.
        # Edit it in \(AppIdentity.name) ▸ Settings ▸ Prompt — changes made here are overwritten.
        """
    }
}

extension PromptSegmentKind {
    /// Segments whose text is computed each prompt and may be empty.
    var isDynamic: Bool {
        switch self {
        case .gitBranch, .exitStatus, .jobs, .pythonEnvironment: true
        case .user, .host, .userAtHost, .directory, .directoryName, .time: false
        }
    }
}
